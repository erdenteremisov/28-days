const NUMERIC_FIELDS: { key: keyof DayEntry; label: string; unit: string; scale5?: boolean }[] = [
  { key: 'sleepHours', label: 'Сон', unit: 'ч' },
  { key: 'sleepQuality', label: 'Качество сна (насколько выспался)', unit: '', scale5: true },
  { key: 'screenTimeHours', label: 'Экранное время', unit: 'ч' },
  { key: 'shortsHours', label: 'Shorts/Reels/TikTok', unit: 'ч' },
  { key: 'workHours', label: 'Работа/учёба', unit: 'ч' },
  { key: 'mainGoalHours', label: 'Главное дело/личная цель', unit: 'ч' },
  { key: 'activityMinutes', label: 'Физическая активность', unit: 'мин' },
  { key: 'energy', label: 'Энергия', unit: '', scale5: true },
  { key: 'satisfaction', label: 'Удовлетворённость днём', unit: '', scale5: true },
  { key: 'tension', label: 'Напряжение', unit: '', scale5: true },
  { key: 'qualityCommunicationHours', label: 'Качественное общение', unit: 'ч' },
  { key: 'unplannedSpendingRub', label: 'Незапланированные траты', unit: '₽' },
];

interface Aggregate {
  label: string;
  unit: string;
  avg: number;
  min: number;
  max: number;
  filledCount: number;
}

function fmtVal(v: number, unit: string, scale5?: boolean): string {
  return scale5 ? `${v}/5` : `${v}${unit}`;
}

function aggregate(days: DayEntry[]): Aggregate[] {
  const result: Aggregate[] = [];
  for (const f of NUMERIC_FIELDS) {
    const values = days.map((d) => d[f.key]).filter((v): v is number => typeof v === 'number');
    if (values.length === 0) continue;
    const avg = values.reduce((a, b) => a + b, 0) / values.length;
    result.push({
      label: f.label,
      unit: f.scale5 ? '/5' : f.unit,
      avg: Math.round(avg * 10) / 10,
      min: Math.min(...values),
      max: Math.max(...values),
      filledCount: values.length,
    });
  }
  return result;
}

function formatDaysTable(days: DayEntry[]): string {
  if (days.length === 0) return '(нет заполненных дней в этом диапазоне)';
  const lines = days.map((d) => {
    const parts = [
      `День ${d.dayNumber}`,
      d.sleepHours != null ? `сон ${d.sleepHours}ч` : null,
      d.sleepQuality != null ? `выспался ${d.sleepQuality}/5` : null,
      d.screenTimeHours != null ? `экран ${d.screenTimeHours}ч` : null,
      d.shortsHours != null ? `шортсы ${d.shortsHours}ч` : null,
      d.workHours != null ? `работа ${d.workHours}ч` : null,
      d.mainGoalHours != null ? `главное дело ${d.mainGoalHours}ч` : null,
      d.activityMinutes != null ? `активность ${d.activityMinutes}мин` : null,
      d.energy != null ? `энергия ${d.energy}/5` : null,
      d.satisfaction != null ? `удовлетворённость ${d.satisfaction}/5` : null,
      d.tension != null ? `напряжение ${d.tension}/5` : null,
      d.qualityCommunicationHours != null ? `общение ${d.qualityCommunicationHours}ч` : null,
      d.unplannedSpendingRub != null ? `траты ${d.unplannedSpendingRub}₽` : null,
      d.note ? `заметка: «${d.note}»` : null,
    ].filter(Boolean);
    return '- ' + parts.join(', ');
  });
  return lines.join('\n');
}

function formatAggregates(aggs: Aggregate[]): string {
  if (aggs.length === 0) return '(недостаточно данных для средних значений)';
  return aggs
    .map((a) => `- ${a.label}: среднее ${fmtVal(a.avg, a.unit)}, минимум ${fmtVal(a.min, a.unit)}, максимум ${fmtVal(a.max, a.unit)} (заполнено дней: ${a.filledCount})`)
    .join('\n');
}

function formatExperiment(exp: Experiment | undefined): string {
  if (!exp || !exp.hypothesis) return '(эксперимент ещё не описан)';
  return [
    `Гипотеза: ${exp.hypothesis}`,
    exp.reason ? `Почему появилась: ${exp.reason}` : null,
    exp.change ? `Что менялось: ${exp.change}` : null,
    exp.expectedResult ? `Ожидаемый результат: ${exp.expectedResult}` : null,
    exp.observations ? `Наблюдения: ${exp.observations}` : null,
    exp.result ? `Результат: ${exp.result}` : null,
    exp.conclusion ? `Вывод пользователя: ${exp.conclusion}` : null,
  ]
    .filter(Boolean)
    .join('\n');
}

// Локальный (не-AI) обзор по стадиям — используется как "первичные аналитические
// наблюдения" в финальном промпте, поскольку приложение не сохраняет тексты
// ответов внешнего AI за предыдущие недели.
function buildAnalysisNotes(days: DayEntry[]): string {
  const stageRanges: { label: string; start: number; end: number }[] = [
    { label: 'Наблюдение (дни 1-7)', start: 1, end: 7 },
    { label: 'Эксперимент №1 (дни 8-14)', start: 8, end: 14 },
    { label: 'Эксперимент №2 (дни 15-21)', start: 15, end: 21 },
    { label: 'Закрепление (дни 22-28)', start: 22, end: 28 },
  ];
  const lines: string[] = [
    '(это не анализ от AI, а локально посчитанные средние по стадиям — предыдущие ответы AI приложение не сохраняет)',
  ];
  for (const range of stageRanges) {
    const stageDays = days.filter((d) => d.dayNumber >= range.start && d.dayNumber <= range.end);
    if (stageDays.length === 0) continue;
    const aggs = aggregate(stageDays);
    const energyAgg = aggs.find((a) => a.label === 'Энергия');
    const satisfactionAgg = aggs.find((a) => a.label === 'Удовлетворённость днём');
    const tensionAgg = aggs.find((a) => a.label === 'Напряжение');
    const parts = [
      energyAgg ? `энергия в среднем ${energyAgg.avg}/5` : null,
      satisfactionAgg ? `удовлетворённость ${satisfactionAgg.avg}/5` : null,
      tensionAgg ? `напряжение ${tensionAgg.avg}/5` : null,
    ].filter(Boolean);
    lines.push(`- ${range.label}, заполнено дней: ${stageDays.length}${parts.length ? ' — ' + parts.join(', ') : ''}`);
  }
  return lines.join('\n');
}

function onboardingBlock(meta: MetaData) {
  return {
    concern: meta.onboardingAnswers?.concern || '(не указано)',
    goal: meta.onboardingAnswers?.goal || '(не указано)',
    change: meta.onboardingAnswers?.changeIfUseful || '(не указано)',
  };
}

