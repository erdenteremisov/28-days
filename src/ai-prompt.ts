// ===================== Форматирование сырых данных дня =====================
// Промпты этой версии не просят агрегаты/средние - только сырые данные по
// дням ("не придумывай отсутствующие значения" - решать, что из этого
// значит, должен сам AI, а не наш локальный расчёт).

function formatWeekData(days: DayEntry[]): string {
  if (days.length === 0) return '(нет заполненных дней в этом диапазоне)';
  const lines = days.map((d) => {
    const parts = [
      `День ${d.dayNumber}`,
      d.sleepHours != null ? `сон ${d.sleepHours}ч` : null,
      d.sleepQuality != null ? `выспался ${d.sleepQuality}/5` : null,
      d.screenTimeHours != null ? `экран ${d.screenTimeHours}ч` : null,
      d.shortsHours != null ? `шортсы ${d.shortsHours}ч` : null,
      d.workHours != null ? `работа ${d.workHours}ч` : null,
      d.mainGoalHours != null ? `главное дело ${d.mainGoalHours}ч` : null,
      d.activityMinutes != null ? `активность ${d.activityMinutes}мин` : null,
      d.energy != null ? `энергия ${d.energy}/5` : null,
      d.satisfaction != null ? `удовлетворённость ${d.satisfaction}/5` : null,
      d.tension != null ? `напряжение ${d.tension}/5` : null,
      d.note ? `заметка: «${d.note}»` : null,
    ].filter(Boolean);
    return '- ' + parts.join(', ');
  });
  return lines.join('\n');
}

function filledCount(days: DayEntry[], rangeStart: number, rangeEnd: number): number {
  return days.filter((d) => d.dayNumber >= rangeStart && d.dayNumber <= rangeEnd).length;
}

function hypothesisText(exp: Experiment | undefined): string {
  return exp && exp.hypothesis.trim() ? exp.hypothesis.trim() : '(гипотеза ещё не сохранена)';
}

interface Onboarding {
  concern: string;
  question: string;
  change: string;
}

function ob(meta: MetaData): Onboarding {
  return {
    concern: meta.onboardingAnswers?.concern || '(не указано)',
    question: meta.onboardingAnswers?.goal || '(не указано)',
    change: meta.onboardingAnswers?.changeIfUseful || '(не указано)',
  };
}

